export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale] ?? dictionaries.es;
}

export function isLocale(value: string): value is Locale {
  return locales.includes(value as Locale);
}

/**
 * Interpola valores en un string de diccionario con placeholders `{clave}`.
 * Se usa para no convertir el diccionario en funciones: sigue siendo un
 * objeto de datos plano, mas facil de revisar y de extender a futuro.
 */
export function formatDictionaryString(template: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template
  );
}
